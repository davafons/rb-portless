# Mirror of packages/portless/src/certs.test.ts
#
# rb-portless builds certificates with Ruby's OpenSSL extension instead of the
# openssl binary (AGENTS.md), so the openssl-CLI fixtures upstream builds
# (SHA-1 leaf, bare-TLD wildcard leaf) are built in-process here, and cert
# inspection uses OpenSSL::X509 in place of crypto.X509Certificate.
# Trust tests never reach the real trust store: the `security`/`sudo` shims
# from test_helper stay on PATH, and Linux trust runs against temp dirs.
module CertsMirror
  include UpstreamCore


  # A CA certificate as generated by affected portless versions (#429): the
  # Basic Constraints extension appears twice, both copies marked critical.
  # Valid until 2126.
  DUPLICATE_BASIC_CONSTRAINTS_CA_PEM = <<~PEM
    -----BEGIN CERTIFICATE-----
    MIIBsDCCAVagAwIBAgIUKKwkp3jNXLMBY0qhAbGiYSnsw9wwCgYIKoZIzj0EAwIw
    HDEaMBgGA1UEAwwRcG9ydGxlc3MgTG9jYWwgQ0EwIBcNMjYwOTIyMDIxODM1WhgP
    MjEyNjA4MjkwMjE4MzVaMBwxGjAYBgNVBAMMEXBvcnRsZXNzIExvY2FsIENBMFkw
    EwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAE/pPl34Nyk3KHVT7TZewweXmxNSVIMEaQ
    mI2PD1r5tZj6ruPwQItA/hm3qkPWZaLwzNEyTrV21X2HiSPXuFLlVqN0MHIwHQYD
    VR0OBBYEFNgvp4nYic3k+GkuVQ7m9VC6ox//MB8GA1UdIwQYMBaAFNgvp4nYic3k
    +GkuVQ7m9VC6ox//MA8GA1UdEwEB/wQFMAMBAf8wDwYDVR0TAQH/BAUwAwEB/zAO
    BgNVHQ8BAf8EBAMCAQYwCgYIKoZIzj0EAwIDSAAwRQIgI37nl7zzEE0DS7IHNirH
    ssY582QVrZyaZ6RJWfhWeEsCIQCAUo4lVo68JwxRysacLYMtqli2idSCZ6hmEA01
    eIP1wQ==
    -----END CERTIFICATE-----
  PEM

  # Ruby's OpenSSL extension always sets notBefore (upstream: openssl >= 3.4).
  LOCAL_OPENSSL_BACKDATES = true

  def x509(path) = OpenSSL::X509::Certificate.new(File.read(path))

  # Signature algorithm of a PEM cert, lowercased.
  def get_cert_signature_algo(cert_path) = x509(cert_path).signature_algorithm.downcase

  # How many times the Basic Constraints extension appears in a PEM cert.
  def count_basic_constraints(cert_path) = x509(cert_path).extensions.count { |e| e.oid == "basicConstraints" }

  def subject_alt_name(cert_path) = x509(cert_path).extensions.find { |e| e.oid == "subjectAltName" }&.value.to_s

  def ca?(cert_path)
    bc = x509(cert_path).extensions.find { |e| e.oid == "basicConstraints" }
    !!bc&.value&.include?("CA:TRUE")
  end

  def fingerprint(cert_path) = OpenSSL::Digest::SHA256.hexdigest(x509(cert_path).to_der)

  # Seconds since a PEM cert's notBefore.
  def cert_age(cert_path) = Time.now - x509(cert_path).not_before

  def ensure_certs(dir) = Portless::Certs.ensure_certs(dir)

  # Sign `key` into `cert_path` with an arbitrary issuer/digest/SAN list.
  def write_cert(cert_path, key:, subject:, issuer_cert: nil, issuer_key: key, digest: "SHA256", days: 365, sans: nil,
                 extra: [])
    cert = OpenSSL::X509::Certificate.new
    cert.version = 2
    cert.serial = OpenSSL::BN.rand(63)
    cert.subject = OpenSSL::X509::Name.parse(subject)
    cert.issuer = issuer_cert ? issuer_cert.subject : cert.subject
    cert.public_key = OpenSSL::PKey.read(key.public_to_pem)
    cert.not_before = Time.now
    cert.not_after = Time.now + days * 86_400
    ef = OpenSSL::X509::ExtensionFactory.new
    ef.subject_certificate = cert
    ef.issuer_certificate = issuer_cert || cert
    extra.each { |(oid, value)| cert.add_extension(ef.create_extension(oid, value)) }
    cert.add_extension(ef.create_extension("subjectAltName", sans)) if sans
    cert.sign(issuer_key, OpenSSL::Digest.new(digest))
    File.write(cert_path, cert.to_pem)
  end
end

describe "sanitizeHostForFilename" do
  include CertsMirror

  # Longest suffix the cert cache appends to the sanitized base.
  def suffix_len = "-key.pem".length
  def name_max = 255

  it "keeps short hostnames readable and unchanged apart from dots" do
    assert_equal "myapp_dev_example_com", Portless::Certs.sanitize_host_for_filename("myapp.dev.example.com")
  end

  it "bounds the composed cert filename under NAME_MAX for a max-length hostname" do
    # A 253-char hostname is valid DNS (multi-segment TLD) but its naive
    # sanitized filename would overflow NAME_MAX and fail with ENAMETOOLONG.
    label = "a" * 63
    hostname = "x.#{label}.#{label}.#{label}.#{'b' * 57}"
    assert_operator hostname.length, :>, name_max - suffix_len
    safe = Portless::Certs.sanitize_host_for_filename(hostname)
    assert_operator safe.length + suffix_len, :<=, name_max
  end

  it "is deterministic so the cert cache still hits for the same host" do
    label = "a" * 63
    hostname = "x.#{label}.#{label}.#{label}.#{'b' * 57}"
    assert_equal Portless::Certs.sanitize_host_for_filename(hostname), Portless::Certs.sanitize_host_for_filename(hostname)
  end

  it "maps distinct overflowing hostnames to distinct filenames" do
    label = "a" * 63
    base = "#{label}.#{label}.#{label}"
    a = Portless::Certs.sanitize_host_for_filename("app1.#{base}.#{'b' * 57}")
    b = Portless::Certs.sanitize_host_for_filename("app2.#{base}.#{'b' * 57}")
    refute_equal a, b
  end
end

