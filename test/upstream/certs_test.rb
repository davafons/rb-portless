describe "ensureCerts" do
  include CertsMirror

  before { @tmp_dir = mkdtemp("portless-certs-test-") }
  after { FileUtils.rm_rf(@tmp_dir) }

  it "generates CA and server certificates on first call" do
    result = ensure_certs(@tmp_dir)

    assert_equal true, result[:ca_generated]
    assert_equal true, File.exist?(result[:cert_path])
    assert_equal true, File.exist?(result[:key_path])
    assert_equal true, File.exist?(result[:ca_path])
  end

  it "backdates the CA and server certs' notBefore when openssl can set it" do
    result = ensure_certs(@tmp_dir)
    if CertsMirror::LOCAL_OPENSSL_BACKDATES
      assert_operator cert_age(result[:ca_path]), :>, 4 * 60
      assert_operator cert_age(result[:ca_path]), :<, 6 * 60
      assert_operator cert_age(result[:cert_path]), :>, 4 * 60
      assert_operator cert_age(result[:cert_path]), :<, 6 * 60
    else
      assert_operator cert_age(result[:ca_path]), :<, 60
      assert_operator cert_age(result[:cert_path]), :<, 60
    end
  end

  it "returns valid PEM certificates" do
    result = ensure_certs(@tmp_dir)

    cert_pem = File.read(result[:cert_path])
    assert_includes cert_pem, "-----BEGIN CERTIFICATE-----"

    key_pem = File.read(result[:key_path])
    assert_includes key_pem, "-----BEGIN EC PRIVATE KEY-----"

    ca_pem = File.read(result[:ca_path])
    assert_includes ca_pem, "-----BEGIN CERTIFICATE-----"
  end

  it "server cert is signed by the CA (different from CA cert)" do
    result = ensure_certs(@tmp_dir)

    server_cert = x509(result[:cert_path])
    ca_cert = x509(result[:ca_path])

    # Server cert issuer should match CA subject
    assert_equal ca_cert.subject.to_s, server_cert.issuer.to_s

    # Server cert should not be the same as CA cert
    refute_equal fingerprint(result[:ca_path]), fingerprint(result[:cert_path])
  end

  it "server cert covers localhost and *.localhost via SAN" do
    result = ensure_certs(@tmp_dir)
    san = subject_alt_name(result[:cert_path])

    assert_includes san, "DNS:localhost"
    assert_includes san, "DNS:*.localhost"
  end

  it "CA cert has CA:TRUE basic constraint" do
    result = ensure_certs(@tmp_dir)

    # The CA cert should be marked as a CA
    assert_equal true, ca?(result[:ca_path])
  end

  it "generates CA and server certs with SHA-256 signatures" do
    result = ensure_certs(@tmp_dir)

    assert_includes get_cert_signature_algo(result[:ca_path]), "sha256"
    assert_includes get_cert_signature_algo(result[:cert_path]), "sha256"
  end

  it "does not duplicate critical extensions when the ambient openssl.cnf sets x509_extensions for req (regression)" do
    fake_system_cnf = File.join(@tmp_dir, "fake-system-openssl.cnf")
    File.write(
      fake_system_cnf,
      [
        "[req]",
        "distinguished_name = req_distinguished_name",
        "x509_extensions = v3_ca",
        "prompt = no",
        "[req_distinguished_name]",
        "CN = localhost",
        "[v3_ca]",
        "basicConstraints = critical,CA:TRUE",
        ""
      ].join("\n")
    )

    with_env("OPENSSL_CONF" => fake_system_cnf) do
      result = ensure_certs(@tmp_dir)
      assert_equal 1, count_basic_constraints(result[:ca_path])
    end
  end

  it "regenerates an existing CA whose Basic Constraints extension is duplicated (#429)" do
    first = ensure_certs(@tmp_dir)
    first_server_cert = File.read(first[:cert_path])

    # Simulate a state dir left behind by an affected version. Expiry and
    # signature algorithm are fine, so only the extension check can catch it.
    File.write(first[:ca_path], CertsMirror::DUPLICATE_BASIC_CONSTRAINTS_CA_PEM)
    assert_equal 2, count_basic_constraints(first[:ca_path])

    second = ensure_certs(@tmp_dir)
    assert_equal true, second[:ca_generated]
    assert_equal 1, count_basic_constraints(second[:ca_path])

    # The server cert chained to the discarded CA, so it must be re-issued too.
    refute_equal first_server_cert, File.read(second[:cert_path])
  end

  it "generates certs when state dir path contains a dot (#152)" do
    dot_dir = File.join(@tmp_dir, "user.name", ".portless")
    FileUtils.mkdir_p(dot_dir)

    result = ensure_certs(dot_dir)

    assert_equal true, result[:ca_generated]
    assert_equal true, File.exist?(result[:cert_path])
    assert_equal true, File.exist?(result[:key_path])
    assert_equal true, File.exist?(result[:ca_path])

    # The .srl file must be inside the state dir, not elsewhere
    srl_path = File.join(dot_dir, "ca.srl")
    assert_equal true, File.exist?(srl_path)
  end

  it "reuses existing certs on second call" do
    first = ensure_certs(@tmp_dir)
    assert_equal true, first[:ca_generated]

    second = ensure_certs(@tmp_dir)
    assert_equal false, second[:ca_generated]

    # Cert files should be the same
    assert_equal File.read(first[:cert_path]), File.read(second[:cert_path])
  end

  it "regenerates server cert if it is deleted" do
    first = ensure_certs(@tmp_dir)
    first_cert = File.read(first[:cert_path])

    # Delete the server cert but keep the CA
    File.unlink(first[:cert_path])

    second = ensure_certs(@tmp_dir)
    assert_equal false, second[:ca_generated] # CA still exists
    assert_equal true, File.exist?(second[:cert_path])

    # New cert should be different (regenerated)
    refute_equal first_cert, File.read(second[:cert_path])
  end

  it "regenerates server cert if it uses SHA-1 signature" do
    first = ensure_certs(@tmp_dir)
    ca_key_path = File.join(@tmp_dir, "ca-key.pem")

    write_cert(
      first[:cert_path],
      key: OpenSSL::PKey.read(File.read(first[:key_path])),
      subject: "/CN=localhost",
      issuer_cert: x509(first[:ca_path]),
      issuer_key: OpenSSL::PKey.read(File.read(ca_key_path)),
      digest: "SHA1",
      sans: "DNS:localhost,DNS:*.localhost",
      extra: [
        %w[authorityKeyIdentifier keyid,issuer], %w[basicConstraints CA:FALSE],
        %w[keyUsage digitalSignature,keyEncipherment], %w[extendedKeyUsage serverAuth]
      ]
    )

    assert_includes get_cert_signature_algo(first[:cert_path]), "sha1"

    second = ensure_certs(@tmp_dir)
    assert_includes get_cert_signature_algo(second[:cert_path]), "sha256"
  end

  it "sets restrictive permissions on key files" do
    result = ensure_certs(@tmp_dir)

    ca_key_path = File.join(@tmp_dir, "ca-key.pem")
    assert_equal 0o600, File.stat(ca_key_path).mode & 0o777

    assert_equal 0o600, File.stat(result[:key_path]).mode & 0o777
  end
end

describe "createSNICallback" do
  include CertsMirror

  before do
    @tmp_dir = mkdtemp("portless-sni-test-")
    certs = ensure_certs(@tmp_dir)
    @default_cert = File.read(certs[:cert_path])
    @default_key = File.read(certs[:key_path])
  end

  after { FileUtils.rm_rf(@tmp_dir) }

  def create_sni_callback(dir, cert, key, *rest) = Portless::Certs.create_sni_callback(dir, cert, key, *rest)

  it "returns default context for localhost" do
    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)
    ctx = sni_callback.call("localhost")

    refute_nil ctx
  end

  it "generates per-hostname cert for single-level subdomains" do
    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)
    ctx = sni_callback.call("myapp.localhost")

    refute_nil ctx

    # Single-level subdomains must get a per-hostname cert with an exact SAN.
    # RFC 2606 §2 reserves ".localhost" as a TLD, so "*.localhost" sits at the
    # public-suffix boundary and wildcard certificates there are not valid per spec.
    host_cert_path = File.join(@tmp_dir, "host-certs", "myapp_localhost.pem")
    assert_equal true, File.exist?(host_cert_path)
    assert_equal "DNS:myapp.localhost", subject_alt_name(host_cert_path)
  end

  it "reissues a cached host cert that has a bare TLD wildcard SAN" do
    host_dir = File.join(@tmp_dir, "host-certs")
    FileUtils.mkdir_p(host_dir)
    key_path = File.join(host_dir, "myapp_localhost-key.pem")
    cert_path = File.join(host_dir, "myapp_localhost.pem")
    key = OpenSSL::PKey::EC.generate("prime256v1")
    File.write(key_path, key.to_pem)
    write_cert(cert_path, key: key, subject: "/CN=myapp.localhost", days: 30,
                          sans: "DNS:myapp.localhost,DNS:*.localhost")

    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)
    sni_callback.call("myapp.localhost")

    assert_equal "DNS:myapp.localhost", subject_alt_name(cert_path)
  end

  it "backdates a host cert's notBefore when openssl can set it" do
    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)
    sni_callback.call("skew.localhost")

    host_cert_path = File.join(@tmp_dir, "host-certs", "skew_localhost.pem")
    if CertsMirror::LOCAL_OPENSSL_BACKDATES
      assert_operator cert_age(host_cert_path), :>, 4 * 60
      assert_operator cert_age(host_cert_path), :<, 6 * 60
    else
      assert_operator cert_age(host_cert_path), :<, 60
    end
  end

  it "generates per-hostname cert for multi-level subdomains" do
    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)
    ctx = sni_callback.call("chat.myapp.localhost")

    refute_nil ctx

    # Verify a cert file was created in the host-certs directory
    host_cert_path = File.join(@tmp_dir, "host-certs", "chat_myapp_localhost.pem")
    assert_equal true, File.exist?(host_cert_path)

    # Verify the generated cert covers the hostname
    assert_includes subject_alt_name(host_cert_path), "DNS:chat.myapp.localhost"
  end

  it "generates per-hostname cert for multi-segment TLDs (issue #260)" do
    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key, "local.example.dev")
    ctx = sni_callback.call("myapp.local.example.dev")

    refute_nil ctx

    host_cert_path = File.join(@tmp_dir, "host-certs", "myapp_local_example_dev.pem")
    assert_equal true, File.exist?(host_cert_path)

    san = subject_alt_name(host_cert_path)
    assert_includes san, "DNS:myapp.local.example.dev"
    # A sibling wildcard at the TLD level covers other apps under the same TLD
    assert_includes san, "DNS:*.local.example.dev"
  end

  it "generates cert for a hostname longer than 64 characters (X.509 CN limit)" do
    long_prefix = "a" * 55
    long_hostname = "service.#{long_prefix}.localhost"
    assert_operator long_hostname.length, :>, 64

    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)
    ctx = sni_callback.call(long_hostname)

    refute_nil ctx

    # Verify the generated cert uses the full hostname in the SAN (not CN).
    # TLS validation relies on SAN, not CN, so the full hostname must be there.
    safe_name = long_hostname.tr(".", "_")
    host_cert_path = File.join(@tmp_dir, "host-certs", "#{safe_name}.pem")
    assert_equal true, File.exist?(host_cert_path)

    assert_includes subject_alt_name(host_cert_path), "DNS:#{long_hostname}"
  end

  it "caches generated certs in memory on subsequent calls" do
    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)

    ctx1 = sni_callback.call("deep.sub.localhost")
    ctx2 = sni_callback.call("deep.sub.localhost")

    # Same context object returned from cache
    assert_same ctx1, ctx2
  end

  it "drops per-hostname certs issued by a previous CA when the CA is regenerated" do
    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)
    sni_callback.call("myapp.localhost")
    host_cert_path = File.join(@tmp_dir, "host-certs", "myapp_localhost.pem")
    stale_host_cert = x509(host_cert_path)

    # Force a CA regeneration, as the #429 migration or an expired CA would.
    File.unlink(File.join(@tmp_dir, "ca.pem"))
    regenerated = ensure_certs(@tmp_dir)
    assert_equal true, regenerated[:ca_generated]
    new_ca = x509(regenerated[:ca_path])

    # The cached host cert no longer chains to the new CA and must be gone,
    # otherwise the SNI callback would keep serving it from disk.
    assert_equal false, stale_host_cert.verify(new_ca.public_key)
    assert_equal false, File.exist?(host_cert_path)

    # A fresh callback re-issues the host cert under the new CA.
    fresh_callback = create_sni_callback(@tmp_dir, File.read(regenerated[:cert_path]),
                                         File.read(regenerated[:key_path]))
    fresh_callback.call("myapp.localhost")
    reissued = x509(host_cert_path)
    assert_equal true, reissued.verify(new_ca.public_key)
  end

  it "refuses hostnames outside the configured TLDs without issuing a cert" do
    sni_callback = create_sni_callback(@tmp_dir, @default_cert, @default_key)
    [
      "outside.example.com",
      "localhost.example.net",
      "evillocalhost",
      "outside.example.com,DNS:app.localhost"
    ].each do |name|
      error = assert_raises(StandardError) { sni_callback.call(name) }
      assert_kind_of StandardError, error
    end
    assert_equal false, File.exist?(File.join(@tmp_dir, "host-certs"))
  end

  it "returns error via callback when state dir is invalid" do
    bad_dir = File.join(@tmp_dir, "nonexistent")
    sni_callback = create_sni_callback(bad_dir, @default_cert, @default_key)

    error = assert_raises(StandardError) { sni_callback.call("deep.sub.localhost") }

    assert_kind_of StandardError, error
  end
end

