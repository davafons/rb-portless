describe "untrustCA" do
  include CertsMirror

  before { @tmp_dir = mkdtemp("portless-untrust-test-") }
  after { FileUtils.rm_rf(@tmp_dir) }

  def untrust_ca_linux(dir, configs:, active_config:, run_update:)
    Portless::Trust.untrust_linux(dir, configs: configs, active_config: active_config, run_update: run_update)
  end

  it "returns removed when ca.pem is missing" do
    assert_equal({ removed: true }, Portless::Trust.untrust_ca(@tmp_dir))
  end

  it "retries a failed Linux trust refresh after the source certificate is gone" do
    ca_path = ensure_certs(@tmp_dir)[:ca_path]
    trust_dir = File.join(@tmp_dir, "linux-trust")
    installed_ca = File.join(trust_dir, Portless::Trust::LINUX_CERT_NAME)
    config = { cert_dir: trust_dir, update_command: "refresh-linux-trust" }
    Dir.mkdir(trust_dir)
    FileUtils.cp(ca_path, installed_ca)

    outcomes = [ -> { raise "trust refresh failed" }, -> { } ]
    run_update = spy { |_command| outcomes.shift.call }

    first = untrust_ca_linux(@tmp_dir, configs: [ config ], active_config: config, run_update: run_update)

    assert_equal({ removed: false, error: "trust refresh failed" }, first)
    assert_equal false, File.exist?(installed_ca)
    assert_equal true, File.exist?(File.join(@tmp_dir, "ca.pem"))
    assert_equal true, File.exist?(File.join(@tmp_dir, "ca-key.pem"))

    second = untrust_ca_linux(@tmp_dir, configs: [ config ], active_config: config, run_update: run_update)

    assert_equal({ removed: true }, second)
    assert_equal [ "refresh-linux-trust" ], run_update.calls[0]
    assert_equal [ "refresh-linux-trust" ], run_update.calls[1]
  end

  it "does not refresh Linux trust when the CA was never installed" do
    ensure_certs(@tmp_dir)
    trust_dir = File.join(@tmp_dir, "linux-trust")
    config = { cert_dir: trust_dir, update_command: "refresh-linux-trust" }
    run_update = spy
    Dir.mkdir(trust_dir)

    assert_equal({ removed: true },
                 untrust_ca_linux(@tmp_dir, configs: [ config ], active_config: config, run_update: run_update))
    refute run_update.called?
  end

  it "replaces a symlinked pending refresh marker without writing to its target" do
    ca_path = File.join(@tmp_dir, "ca.pem")
    File.write(ca_path, "-----BEGIN CERTIFICATE-----\ntest\n-----END CERTIFICATE-----\n")
    trust_dir = File.join(@tmp_dir, "linux-trust")
    installed_ca = File.join(trust_dir, Portless::Trust::LINUX_CERT_NAME)
    outside_target = File.join(@tmp_dir, "outside-target")
    pending_link = File.join(@tmp_dir, "ca.trust-refresh-pending")
    config = { cert_dir: trust_dir, update_command: "refresh-linux-trust" }
    Dir.mkdir(trust_dir)
    FileUtils.cp(ca_path, installed_ca)
    File.symlink(outside_target, pending_link)

    run_update = spy { |_command| raise "trust refresh failed" }

    result = untrust_ca_linux(@tmp_dir, configs: [ config ], active_config: config, run_update: run_update)

    assert_equal({ removed: false, error: "trust refresh failed" }, result)
    assert_equal false, File.exist?(outside_target)
    assert_equal false, File.lstat(pending_link).symlink?
    assert_equal "1\n", File.read(pending_link)
  end
